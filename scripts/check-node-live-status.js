#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const app=fs.readFileSync('app.js','utf8');
const css=fs.readFileSync('styles.css','utf8');
const runtime=fs.readFileSync('backend/src/node_runtime.rs','utf8');
assert.match(app,/data-node-card-id/);
assert.match(app,/data-node-runtime-state/);
assert.match(app,/data-node-xray-version/);
assert.match(app,/async function refreshNodeRuntime\(\)/);
assert.match(app,/Promise\.all\(\[refreshNodeMetrics\(\),refreshNodeRuntime\(\)\]\)/);
assert.match(app,/setInterval\(\(\)=>\{void poll\(\)\},5000\)/);
// Evaluate the actual status decision, not its source formatting.
const vm=require('node:vm');
const stateStart=app.indexOf('const nodeRuntimeState=');
const stateEnd=app.indexOf('const nodeAgentUpdating=',stateStart);
assert(stateStart>=0&&stateEnd>stateStart,'Node runtime state function must exist');
const state=vm.runInNewContext(app.slice(stateStart,stateEnd)+';nodeRuntimeState');
const healthy={connected:true,xrayRunning:true,routerRunning:true};
assert.equal(state({disabled:false},healthy).kind,'online');
assert.equal(state({disabled:false},{...healthy,connected:false,lastSeenAt:Date.now()}).kind,'offline','Stale heartbeats must never mark a node active');
assert.equal(state({disabled:false},{...healthy,xrayRunning:false}).kind,'offline','Stopped Xray must not mark node active');
assert.equal(state({disabled:false},{...healthy,routerRunning:false}).kind,'offline','Stopped router must not mark node active');
assert.equal(state({disabled:true},healthy).kind,'offline','A disabled node must not be reported online while Xray is running');
assert.equal(state({disabled:true},{...healthy,xrayRunning:false}).kind,'disabled','Only confirmed shutdown marks disabled state');
assert.equal(state({disabled:false},{connected:true}).kind,'unknown','Missing service state must not imply online');
assert.match(app,/version\\.textContent\\s*=\\s*runtime\\?\\.xrayVersion\\s*\\?/,'Remote Xray version must be rendered using textContent');
assert.doesNotMatch(app,/version\\.innerHTML\\s*=\\s*runtime/,'Untrusted node version must never be parsed as HTML');
assert.match(css,/\.node-runtime-online/);
assert.match(css,/\.node-runtime-offline/);
assert.match(runtime,/"xrayVersion":row\.try_get/);
assert.match(runtime,/received_at > NOW\(\) - INTERVAL '65 seconds'/);
console.log('Live Xray and node state contract: OK');
