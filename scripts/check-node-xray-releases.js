#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {spawnSync}=require('node:child_process');
const core=fs.readFileSync('backend/src/core.rs','utf8');
const runtime=fs.readFileSync('backend/src/node_runtime.rs','utf8');
const routes=fs.readFileSync('backend/src/main.rs','utf8');
const migration=fs.readFileSync('backend/migrations/0023_xray_release_target.sql','utf8');
const agent=fs.readFileSync('deploy/node-control-agent.sh','utf8');
const updater=fs.readFileSync('deploy/update-node-control-agent.sh','utf8');
const ui=fs.readFileSync('app.js','utf8');
assert.match(core,/pub async fn all_node_releases\(&self\)/);
assert.match(core,/releases\?per_page=100&page=\{page\}/);
assert.match(core,/if count<100\{break\}/);
assert.match(core,/node_release_cache/);
assert.match(core,/prerelease:r\.prerelease/);
assert.match(routes,/\/nodes\/xray-releases/);
assert.match(runtime,/pub async fn available_xray_releases/);
assert.match(runtime,/pub struct XrayVersionRequest\{version:String\}/);
const restart=runtime.slice(runtime.indexOf('pub async fn request_restart('),runtime.indexOf('pub async fn available_xray_releases('));
assert.doesNotMatch(restart,/XrayVersionRequest/,'Ordinary restarts must remain bodyless');
assert.match(restart,/control-v3/,'The new agent must still be able to restart Xray');
const update=runtime.slice(runtime.indexOf('pub async fn request_xray_update('),runtime.indexOf('pub async fn restart_status('));
assert.match(update,/Json\(body\): Json<XrayVersionRequest>/);
assert.match(update,/releases\.iter\(\)\.any\(\|r\|r\.version==target\)/);
assert.match(update,/version LIKE 'control-v3%'/);
assert.match(update,/target_version/);
assert.match(update,/\.bind\(&actor\.username\)\.bind\(target\)/);
assert.match(runtime,/RETURNING id,action,target_version/);
assert.match(runtime,/"targetVersion":row\.try_get/);
assert.match(migration,/ADD COLUMN target_version TEXT/);
assert.match(agent,/control-v4[.]0[.]0/);
assert.match(agent,/update_managed_xray "\$target_version"/);
assert.match(agent,/local image_tag="\$\{version#v\}"/);
assert.match(agent,/ghcr\.io\/xtls\/xray-core:\$image_tag/);
assert.match(agent,/persist_pinned_xray_image/);
assert.match(updater,/xmesh-xray-sync\.sh/);
assert.match(updater,/pinned-image/);
assert.match(ui,/const selectNodeXrayRelease=/);
assert.match(ui,/Pre-release/);
assert.match(ui,/xray-release-search/);
assert.match(ui,/\/api\/v1\/nodes\/xray-releases/);
assert.match(ui,/body:JSON\.stringify\(\{version\}\)/);
for(const file of ['deploy/node-control-agent.sh','deploy/update-node-control-agent.sh']){
 const lint=spawnSync('bash',['-n',file],{encoding:'utf8'});
 assert.equal(lint.status,0,file+': '+lint.stderr);
}
console.log('Pinned Xray releases, prereleases, safe agent update: OK');
