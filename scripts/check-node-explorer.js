#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const app=fs.readFileSync('app.js','utf8');
const css=fs.readFileSync('styles.css','utf8');
const html=fs.readFileSync('index.html','utf8');
new Function(app);
const start=app.indexOf('const NODE_EXPLORER_PAGE_SIZE=48;');
const stop=app.indexOf('function nodeExplorerUpdate(){',start);
assert(start>0&&stop>start,'Fleet search helpers must be present');
const nodeRotationSource=app.match(/const nodeRotationIPs = node => [^\n]+/)?.[0];
assert(nodeRotationSource,'Search must use the real rotation-IP parser');
const logic=nodeRotationSource+'\n'+app.slice(start,stop);
const funcs=new Function('viewerMode',logic+';return {size:NODE_EXPLORER_PAGE_SIZE,nodeSearchTerms,nodeSearchEntry,nodeExplorerMatch,nodeExplorerSort};')(()=>false);
assert.equal(funcs.size,48,'Do not mount every node in the DOM');
const first={id:7,name:'Нидерланды',addr:'203.0.113.7',hosting:'Hetzner',flag:'NL',rotationIps:'192.0.2.44',disabled:false};
const second={id:11,name:'Польша',addr:'198.51.100.8',hosting:'',flag:'PL',disabled:true};
const host=[{address:'edge.example.net',sni:'secure.example.net',remark:'EU endpoint',countryCode:'NL'}];
const entries=[funcs.nodeSearchEntry(first,{name:'VLESS Main'},null,host,true),funcs.nodeSearchEntry(second,{name:'Backup'},null,[],false)];
const select=(text,status='all',hosting=false)=>entries.filter(e=>funcs.nodeExplorerMatch(e,funcs.nodeSearchTerms(text),status,hosting)).map(e=>e.id);
for(const query of ['нидерланды','203.0.113.7','192.0.2.44','hosting:hetzner','provider:hetzner','profile:vless','domain:edge.example.net','domain:secure.example.net','country:nl','id:7','name:"НИДЕРЛАНДЫ"'])assert.deepEqual(select(query),[7],'Search failed: '+query);
assert.deepEqual(select('hosting:hetzner profile:vless'),[7],'Compound AND filters');
assert.deepEqual(select('profile:backup'),[11],'Profile lookup');
assert.deepEqual(select('', 'enabled'),[7],'Enabled-only filter');
assert.deepEqual(select('', 'disabled'),[11],'Disabled-only filter');
assert.deepEqual(select('', 'monitored'),[7],'Fresh metrics filter');
assert.deepEqual(select('', 'unmonitored'),[11],'Unmonitored filter');
assert.deepEqual(select('', 'all',true),[7],'Hosting required filter');
assert.deepEqual(select('no-such-host'),[],'Unknown query returns no matches');
const viewerFuncs=new Function('viewerMode',logic+';return {nodeSearchTerms,nodeSearchEntry,nodeExplorerMatch};')(()=>true);
const viewerEntry=viewerFuncs.nodeSearchEntry(first,{name:'VLESS Main'},null,host,true);
assert(!viewerFuncs.nodeExplorerMatch(viewerEntry,viewerFuncs.nodeSearchTerms('203.0.113.7'),'all',false),'Viewer cannot infer masked IP by search');
assert(!viewerFuncs.nodeExplorerMatch(viewerEntry,viewerFuncs.nodeSearchTerms('edge.example.net'),'all',false),'Viewer cannot infer hidden host domains by search');
const many=Array.from({length:1200},(_,i)=>funcs.nodeSearchEntry({id:i+1,name:'Node-'+i,addr:'10.0.'+Math.floor(i/256)+'.'+(i%256),hosting:i%2?'Provider B':'Provider A',disabled:i%10===0},{name:'profile'},null,[],true));
assert.equal(many.length,1200);
assert.equal(many.filter(e=>funcs.nodeExplorerMatch(e,funcs.nodeSearchTerms('hosting:"provider a"'),'all',false)).length,600);
assert.equal(many.slice(0,funcs.size).length,48);
assert.match(app,/grid\.innerHTML=visible\.map\(/,'Only visible page cards enter the DOM');
assert.match(app,/const pages=Math\.max\(1,Math\.ceil\(filtered\.length\/NODE_EXPLORER_PAGE_SIZE\)\)/,'Stable page count');
assert.match(app,/const hostsByNode=new Map\(\)/,'Assigned hosts indexed for domain searches');
assert.match(app,/runtimeQueue:\[\],runtimePending:new Set\(\),runtimeActive:0,runtimeCache:new Map\(\)/,'Runtime requests cached and queued by node');
assert.match(app,/while\(explorer\.runtimeActive<8&&explorer\.runtimeQueue\.length/,'Limit concurrent node runtime requests to eight');
assert.match(app,/explorer\.runtimeQueue=explorer\.runtimeQueue\.filter/,'Drop queued requests that are no longer visible');
assert.match(app,/setTimeout\(\(\)=>\{if\(!root\.isConnected\)return;nodeExplorer\.page=1;nodeExplorerUpdate\(\)\},140\)/,'Debounced input');
assert.match(css,/\.nodes-page \.node-explorer\{/,'Dedicated themed filter bar');
assert.match(html,/app\.js\?v=20261025-node-explorer-v1/,'Cache-busted explorer script');
console.log('Fleet explorer search/filter/sort and 1,200-node pagination: PASS.');
