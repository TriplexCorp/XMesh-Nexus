#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const main=fs.readFileSync('backend/src/main.rs','utf8');
const auth=fs.readFileSync('backend/src/auth.rs','utf8');
const accounts=fs.readFileSync('backend/src/admin_accounts.rs','utf8');
const migration=fs.readFileSync('backend/migrations/0008_admin_rbac.sql','utf8');
const ui=fs.readFileSync('app.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const getHandler=(name)=>{
 const start=main.indexOf('async fn '+name+'(');
 assert(start>=0,'Missing backend handler '+name);
 return main.slice(start,main.indexOf('\nasync fn ',start+10)===-1?start+4500:main.indexOf('\nasync fn ',start+10));
};
assert.match(migration,/ALTER TABLE panel_auth_users/);
assert.match(migration,/role IN \('owner','admin','viewer'\)/);
assert.match(auth,/pub role: String/);
assert.match(auth,/SELECT a\.id, a\.username, a\.role/);
assert.match(auth,/row\.try_get\("role"\)/);
assert.match(auth,/\"role\": role/);
assert.match(main,/mod admin_accounts;/);
assert.match(main,/\.route\(\s*"\/admins"\s*,\s*get\(admin_accounts::list\)\.post\(admin_accounts::create\)\s*,?\s*\)/);
assert.match(main,/\.route\(\s*"\/admins\/\{id\}"\s*,\s*patch\(admin_accounts::update\)\.delete\(admin_accounts::delete\)\s*,?\s*\)/);
assert.match(main,/fn enforce_collection/);
assert.match(main,/matches!\(collection, "admins" \| "tokens"\)/);
for(const action of ['create_record','update_record','delete_record'])
 assert.match(getHandler(action),/enforce_collection\(&actor, &collection, true\)/,action+' must authorize writes');
assert.match(getHandler('list_records'),/enforce_collection\(&actor, &collection, false\)/);
assert.match(getHandler('bootstrap'),/admin_accounts::accounts\(&state\.pool\)/);
assert.match(getHandler('patch_settings'),/require_owner\(&actor\)/);
assert.match(getHandler('update_core'),/require_owner\(&actor\)/);
assert.match(getHandler('create_node_metrics_token'),/require_owner\(&actor\)/);
assert.match(getHandler('generate_vless_encryption'),/require_mutation\(&actor\)/);
assert.match(fs.readFileSync('backend/src/node_rotation.rs','utf8'),/super::require_mutation\(&actor\)/);
assert.match(accounts,/WHERE role='owner' FOR UPDATE/);
assert.match(accounts,/Нельзя удалить последнего активного владельца/);
assert.match(accounts,/Нельзя отключить последнего активного владельца/);
assert.match(accounts,/DELETE FROM panel_sessions WHERE admin_id=\$1/);
assert.match(accounts,/Argon2::default\(\)\s*\.hash_password/);
assert.match(accounts,/password_hash/);
assert.doesNotMatch(accounts,/serde_json::to_value\(&body\)/,'Never echo submitted passwords');
assert.match(ui,/\/api\/v1\/admins/);
assert.match(ui,/sessionUser=session\.user/);
assert.match(ui,/role==='owner'/);
assert.doesNotMatch(ui,/lm_['"]\+Math\.random\(\)/,'Fake tokens must not be issued');
assert.match(ui,/Выдача API-токенов для интеграций ещё не реализована/);
assert.match(main,/content-security-policy/);
assert.match(main,/sec-fetch-site/);
assert.match(main,/script-src 'self'/);
assert.match(index,/app\.js\?v=/);
console.log('RBAC account separation, server-side authorization, no fake tokens, CSP and CSRF guards: OK');
