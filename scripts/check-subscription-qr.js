#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const qrSource=fs.readFileSync('qr-code.js','utf8');
const qrcodegen=new Function(qrSource+';return qrcodegen;')();
const sample='https://free-tier.shop/subscription/0123456789abcdef0123456789abcdef';
const qr=qrcodegen.QrCode.encodeText(sample,qrcodegen.QrCode.Ecc.MEDIUM);
assert(qr.size>=21&&qr.getModule(0,0),'Bundled encoder must encode a realistic subscription URL');
const portal=fs.readFileSync('subscription-portal.js','utf8');
assert.match(portal,/window\.qrcodegen\?\.QrCode/,'Subscription portal must use the bundled qrcodegen global');
assert.doesNotMatch(portal,/window\.qrgen\?\.QrCode/,'Broken qrgen alias must not return');
assert.match(portal,/new URL\(raw, window\.location\.origin\)/,'Relative subscription paths must resolve against the visitor origin');
assert.match(portal,/input\.value = subscriptionUrl/,'All subscription actions must share the canonical absolute URL');
assert.match(portal,/navigator\.clipboard\.writeText\(subscriptionUrl\)/,'Copy must use the canonical absolute subscription URL');
assert.doesNotMatch(portal,/navigator\.clipboard\.writeText\(input\.value\)/,'Copy must not regress to the raw backend path');
assert.match(portal,/Qr\.encodeText\(subscriptionUrl, Qr\.Ecc\.MEDIUM\)/,'QR must encode the same canonical absolute URL as copy');
assert.match(portal,/const quiet = 4/,'Subscription QR must include a four-module quiet zone');
assert.match(portal,/x \+ quiet/);
assert.match(portal,/y \+ quiet/);
assert.match(portal,/compactSubscriptionUrl/,'Portal should show a shortened bearer URL rather than dumping the full token on screen');
const template=fs.readFileSync('backend/src/subscription_template.html','utf8');
const publicCss=fs.readFileSync('subscription-public.css','utf8');
assert.match(template,/subscription-portal\.js\?v=20261101-absolute-url-enterprise-v2/,'Public portal must cache-bust the absolute URL fix');
assert.match(template,/subscription-public\.css\?v=20261101-enterprise-workspace-v3/,'Public portal must cache-bust the enterprise workspace redesign');
assert.match(template,/id="subscription-link-card"/,'Public portal must expose the enterprise subscription link surface');
assert.match(template,/class="subscription-public-workspace"/,'Public portal must use the workspace composition layer');
assert.match(template,/class="subscription-public-brand-identity"/,'Public portal must expose a product-header identity group');
assert.match(template,/class="subscription-public-status-stack"/,'Public portal status must be grouped as an operational rail');
assert.match(publicCss,/grid-template-columns:minmax\(0,8fr\) minmax\(330px,4fr\)/,'Desktop portal must use an 8/4 enterprise grid');
assert.match(publicCss,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/,'Desktop client catalog must use four balanced columns');
assert.doesNotMatch(template,/>01<|>02</,'Enterprise portal must not expose decorative numbered panels');
console.log('Subscription absolute URL / QR / enterprise workspace contract: OK');
