// Sender-constrained service token and XMesh Sub management security contract.
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const auth=read('backend/src/integration_api_auth.rs');
const proof=read('backend/src/integration_api_proof.rs');
const migration=read('backend/migrations/0122_integration_sender_constrained_tokens.sql');
const grant=read('backend/src/integration_api_grants.rs');
const create=read('backend/src/integration_api_user_mutations.rs');
const sub=read('backend/src/sub_server.rs');
const flood=read('backend/src/subscription_flood.rs');
const studio=read('frontend/js/features/subscriptions/subscription-studio.js');

assert.match(migration,/ADD COLUMN proof_public_key BYTEA/,'Public proof key must be immutable on token creation');
assert.match(migration,/max_grant_days INTEGER/,'Grant cap must be persisted');
assert.match(migration,/max_creates_per_day INTEGER/,'Provision cap must be persisted');
assert.match(auth,/All new API tokens require an Ed25519 proofPublicKey/,'New service tokens must not be bearer-only');
assert.match(auth,/VerifyingKey::from_bytes/,'Public keys must be validated at issuance');
assert.match(auth,/proof::constrain/,'Every protected request must carry a verified proof');
assert(auth.indexOf('proof::constrain') < auth.indexOf('throttle_token(&state, principal.token_id)'),
 'A stolen bearer without proof must not exhaust the per-token request budget');
assert.match(auth,/maxCreatesPerDay/,'Owner must see issued account caps');
assert.match(auth,/XMESH_INTEGRATION_REQUIRE_PROOF/,'Legacy token cutover must be explicitly controllable');
assert.match(read('compose.yaml'),/XMESH_INTEGRATION_REQUIRE_PROOF/,'Runtime must expose strict cutover control');
assert.match(proof,/proof_message\(/,'Signed canonical request binding required');
assert.match(proof,/Sha256::digest\(body\)/,'HTTP body hash must be signed');
assert.match(proof,/path_and_query\(\)/,'Signed URI includes exact query string');
assert.match(proof,/token_hash/,'Signature must be bound to bearer');
assert.match(proof,/redis::cmd\("SET"\)/,'Nonce replay must be protected by Redis');
assert.match(proof,/\.arg\("NX"\)/,'Nonce must be single-use');
assert.match(proof,/\.arg\("EX"\)/,'Nonce expiration must be bounded');
assert.doesNotMatch(proof,/Box::leak|unwrap_unchecked/,'Proof parsing cannot leak memory or use unchecked unsafe code');
assert.match(grant,/max_grant_days\s*\.is_some_and/,'Per-token grant cap must apply');
assert.match(create,/max_creates_per_day/,'Per-client creation cap must apply');
assert.match(create,/FROM integration_clients WHERE id=\$1 FOR UPDATE/,'Concurrent issuance must serialize per integration client');
assert.match(create,/completed_at > NOW\(\) - INTERVAL '24 hours'/,'Only committed issuance within 24h counts');
assert.match(sub,/SUB_AGENT_RATE_PER_MINUTE/,'Sub agent polling must be rate limited');
assert.match(sub,/SUB_CLAIM_GLOBAL_PER_MINUTE/,'Sub enrollment claims must be rate limited');
assert.match(sub,/headers\.contains_key\(header::COOKIE\)/,'Sub agent must reject browser cookie auth');
assert.match(flood,/mode: "protect"/,'Fresh subscription installations must protect from flooding');
assert.match(studio,/subscriptionFlood:\{enabled:true,mode:'protect',ipPerMinute:120,tokenPerMinute:30\}/,'Studio must reflect protected default');
console.log('Integration sender proof, scoped mutation policy and XMesh Sub protection: PASS');
