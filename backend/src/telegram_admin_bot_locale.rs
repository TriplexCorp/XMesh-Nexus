#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn translation_is_explicit_and_bilingual() {
        assert_eq!(Language::from_db("en"), Some(Language::En));
        assert!(Language::from_db("de").is_none());
        assert_eq!(render(Language::Ru, "Пользователи"), "Пользователи");
        assert_eq!(render(Language::En, "👥 Пользователи"), "👥 Users");
        assert_eq!(
            render(Language::En, "Осталось: 30 дн."),
            "Remaining: 30 days"
        );
    }
}
